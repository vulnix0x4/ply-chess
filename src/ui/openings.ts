export const OPENINGS: Opening[] = RAW.map(([eco, name, moves]) => ({ eco, name, moves: moves.split(' ') }));

// Finds the longest opening whose moves are a prefix of the given SAN sequence.
export function findOpening(sans: string[]): Opening | null {
  let best: Opening | null = null;
  for (const o of OPENINGS) {
    if (o.moves.length > sans.length) continue;
    if (best && o.moves.length < best.moves.length) continue;
    let ok = true;
    for (let i = 0; i < o.moves.length; i++) if (o.moves[i] !== sans[i]) { ok = false; break; }
    if (ok) best = o;
  }
  return best;
}

// Candidate next moves (SAN) from the opening table for the given prefix.
export function bookMoves(sans: string[]): string[] {
  const out = new Set<string>();
  for (const o of OPENINGS) {
    if (o.moves.length <= sans.length) continue;
    let ok = true;
    for (let i = 0; i < sans.length; i++) if (o.moves[i] !== sans[i]) { ok = false; break; }
    if (ok) out.add(o.moves[sans.length]);
  }
  return [...out];
}
